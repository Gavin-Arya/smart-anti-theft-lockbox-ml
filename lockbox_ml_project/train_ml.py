import argparse
import itertools
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.ensemble import ExtraTreesClassifier, RandomForestClassifier
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix, f1_score
from sklearn.model_selection import GroupKFold

HERE = Path(".")
CSV_PATH = HERE / "data.csv"
OUT_H = HERE / "lockbox" / "model.h"
REPORT = HERE / "training_report.txt"

FEATURES = ["acc_mean", "acc_std", "acc_max", "acc_peaks", "mic_peak", "mic_mean", "mic_peaks",
            "jerk_mean", "ax_std", "ay_std", "az_std",
            "gyro_mean", "gyro_max", "gyro_net", "acc_cross"]
DERIVED = ["burst", "cv", "mic_per_acc", "mic_burst", "axis_dom", "gyro_burst", "rot_ratio"]
NEEDED = {"idle", "knock", "shake", "carried"}
N_RAW, N_EXT = 15, 22


def extend(X):
    """15 raw features -> 22 (7 derived). Same formulas are generated in C, in float32."""
    X = np.asarray(X, dtype=np.float32)
    f = np.float32
    am, asd, amax, mp, mm = X[:, 0], X[:, 1], X[:, 2], X[:, 4], X[:, 5]
    axs, ays, azs = X[:, 8], X[:, 9], X[:, 10]
    gm, gx, gn = X[:, 11], X[:, 12], X[:, 13]
    d = np.column_stack([
        amax / (am + f(0.02)),                                         
        asd / (am + f(0.02)),
        mp / (amax + f(0.1)),                                          
        mp / (mm + f(1.0)),                                            
        np.maximum(np.maximum(axs, ays), azs) / (axs + ays + azs + f(0.001)),  
        gx / (gm + f(1.0)),                                            
        gn / (gm * f(2.0) + f(1.0)),                                   
    ]).astype(np.float32)
    return np.hstack([X, d])


def make_model(kind, n, depth, leaf):
    cls = RandomForestClassifier if kind == "rf" else ExtraTreesClassifier
    return cls(n_estimators=n, max_depth=depth, min_samples_leaf=leaf,
               class_weight="balanced", random_state=1, n_jobs=-1)


def hard_vote(model, X, n_classes):
    """Majority vote of the trees - exactly what the C code on the ESP32 does."""
    votes = np.stack([t.predict(X) for t in model.estimators_]).astype(int)
    counts = np.apply_along_axis(np.bincount, 0, votes, minlength=n_classes)
    return counts.argmax(axis=0)


def cv_predict(make, X, y, groups, n_classes, folds):
    oof = np.zeros(len(y), dtype=int)
    for tr, te in GroupKFold(n_splits=folds).split(X, y, groups):
        oof[te] = hard_vote(make().fit(X[tr], y[tr]), X[te], n_classes)
    return oof


def alarm_stats(y, pred, alarm_ids, ok_ids):
    """False alarm = idle/knock predicted as an alarm class. Miss = alarm class predicted as idle/knock."""
    y_alarm, p_alarm = np.isin(y, alarm_ids), np.isin(pred, alarm_ids)
    ok = np.isin(y, ok_ids)
    fa = (p_alarm & ok).sum() / max(1, ok.sum())
    miss = (~p_alarm & y_alarm).sum() / max(1, y_alarm.sum())
    return fa, miss


# ---------- C export ----------
def c_float(v):
    s = f"{float(v):.8g}"
    if "." not in s and "e" not in s and "n" not in s:
        s += ".0"
    return s + "f"


def tree_to_c(est, idx):
    t = est.tree_
    out = [f"static int tree{idx}(const float *x) {{"]

    def rec(node, depth):
        pad = "  " * depth
        if t.children_left[node] == -1:
            out.append(f"{pad}return {int(np.argmax(t.value[node][0]))};")
        else:
            out.append(f"{pad}if (x[{t.feature[node]}] <= {c_float(t.threshold[node])}) {{")
            rec(t.children_left[node], depth + 1)
            out.append(f"{pad}}} else {{")
            rec(t.children_right[node], depth + 1)
            out.append(f"{pad}}}")

    rec(0, 1)
    out.append("}")
    return "\n".join(out)


def export_header(model, classes, use_ext, merged, path):
    n = len(classes)
    lines = ["// Auto-generated by train.py - do not edit", "#pragma once", "#include <math.h>",
             f"#define ML_N_CLASSES {n}"]
    lines += [f"#define CLS_{c.upper()} {i}" for i, c in enumerate(classes)]
    if merged:   # lockbox.ino still tests CLS_SHAKE / CLS_CARRIED: both mean "tamper" now
        lines += ["#define CLS_SHAKE CLS_TAMPER", "#define CLS_CARRIED CLS_TAMPER"]
    names = ", ".join(f'"{c}"' for c in classes)
    lines.append(f"const char* CLASS_NAMES[ML_N_CLASSES] = {{{names}}};\n")
    lines += [tree_to_c(e, i) for i, e in enumerate(model.estimators_)]
    calls = "\n".join(f"  votes[tree{i}(z)]++;" for i in range(len(model.estimators_)))
    ext = ""
    if use_ext:
        ext = """  z[15] = x[2] / (x[0] + 0.02f);
  z[16] = x[1] / (x[0] + 0.02f);
  z[17] = x[4] / (x[2] + 0.1f);
  z[18] = x[4] / (x[5] + 1.0f);
  z[19] = fmaxf(fmaxf(x[8], x[9]), x[10]) / (x[8] + x[9] + x[10] + 0.001f);
  z[20] = x[12] / (x[11] + 1.0f);
  z[21] = x[13] / (x[11] * 2.0f + 1.0f);
"""
    lines.append(f"""
// x = the 15 features from features.h (same order as the CSV columns)
int mlPredict(const float *x) {{
  float z[{N_EXT}];
  for (int i = 0; i < {N_RAW}; i++) z[i] = x[i];
{ext}  int votes[ML_N_CLASSES] = {{0}};
{calls}
  int best = 0;
  for (int i = 1; i < ML_N_CLASSES; i++) if (votes[i] > votes[best]) best = i;
  return best;
}}""")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--merge", action="store_true", help="merge shake and carried into one class (tamper)")
    ap.add_argument("--fast", action="store_true", help="skip the model search")
    args = ap.parse_args([])   # notebook: 4 classes (add "--merge" inside the list to merge shake+carried)
    merged = args.merge

    if not CSV_PATH.exists():
        sys.exit("data.csv not found next to train.py.")
    df = pd.read_csv(CSV_PATH)
    if any(c not in df.columns for c in FEATURES):
        sys.exit("data.csv has the OLD format (7 features). Record again with the new logger "
                 "(python3 collect.py --reset), then train.")
    print("Records per class:\n", df["label"].value_counts().to_string(), f"\nTotal: {len(df)}\n")
    if NEEDED - set(df["label"]):
        sys.exit(f"Missing classes in the data: {sorted(NEEDED - set(df['label']))}")

    # ---- labels ----
    y4_names = sorted(df["label"].unique())
    y4 = df["label"].map({c: i for i, c in enumerate(y4_names)}).to_numpy()
    if merged:
        lab = df["label"].replace({"shake": "tamper", "carried": "tamper"})
        classes = sorted(lab.unique())                       # idle, knock, tamper
        y = lab.map({c: i for i, c in enumerate(classes)}).to_numpy()
        alarm_ids, ok_ids = [classes.index("tamper")], [classes.index("idle"), classes.index("knock")]
    else:
        classes, y = y4_names, y4
        alarm_ids = [classes.index("shake"), classes.index("carried")]
        ok_ids = [classes.index("idle"), classes.index("knock")]
    n = len(classes)

    Xraw = df[FEATURES].to_numpy(dtype=np.float32)
    Xext = extend(Xraw)
    groups = df["session"].to_numpy()
    folds = min(5, len(set(groups)))

    # ---- baseline = small forest on the raw features (10 trees, depth 7) ----
    base_oof4 = cv_predict(lambda: make_model("rf", 10, 7, 3), Xraw, y4, groups, len(y4_names), folds)
    if merged:
        to3 = {i: classes.index("tamper" if c in ("shake", "carried") else c) for i, c in enumerate(y4_names)}
        base_pred = np.array([to3[p] for p in base_oof4])
    else:
        base_pred = base_oof4
    base_acc = accuracy_score(y, base_pred)
    base_fa, base_miss = alarm_stats(y, base_pred, alarm_ids, ok_ids)
    print(f"Baseline (small forest, raw features): accuracy {base_acc:.3f}  false alarms {base_fa:.1%}  missed tamper {base_miss:.1%}")

    # ---- search ----
    if args.fast:
        grid = [("rf", True, 30, 8, 3)]
    else:
        grid = list(itertools.product(["rf", "et"], [False, True], [20, 40], [6, 8], [2, 5]))
    results = []
    for kind, ext, ntree, depth, leaf in grid:
        X = Xext if ext else Xraw
        pred = cv_predict(lambda: make_model(kind, ntree, depth, leaf), X, y, groups, n, folds)
        fa, miss = alarm_stats(y, pred, alarm_ids, ok_ids)
        results.append(dict(kind=kind, ext=ext, trees=ntree, depth=depth, leaf=leaf, pred=pred,
                            acc=accuracy_score(y, pred), f1=f1_score(y, pred, average="macro"), fa=fa, miss=miss))
    results.sort(key=lambda r: (-r["f1"], r["trees"]))
    best = results[0]

    rep = [f"Cross-validation by session ({folds} folds, whole sessions held out), hard-vote forest",
           f"Classes: {classes}   (shake and carried merged: {merged})",
           f"Real records: {len(df)}", "",
           f"Baseline (10 trees, depth 7, raw features): accuracy {base_acc:.3f}, "
           f"false alarms {base_fa:.1%}, missed tamper {base_miss:.1%}", "",
           "Top settings tried (ranked by macro F1; the best of many tries is slightly optimistic):"]
    for r in results[:6]:
        rep.append(f"  {r['kind'].upper():2s} derived={str(r['ext']):5s} trees={r['trees']:2d} depth={r['depth']} "
                   f"leaf={r['leaf']}  acc={r['acc']:.3f} f1={r['f1']:.3f} false-alarm={r['fa']:.1%} miss={r['miss']:.1%}")
    rep += ["", f"CHOSEN: {best['kind'].upper()}, derived features={best['ext']}, trees={best['trees']}, "
                f"depth={best['depth']}, min leaf={best['leaf']}",
            f"Accuracy: {best['acc']:.3f}", "",
            classification_report(y, best["pred"], target_names=classes, digits=3),
            "Confusion matrix (rows = real, columns = predicted)", f"classes: {classes}",
            str(confusion_matrix(y, best["pred"])), "",
            f"False alarms (idle/knock predicted as alarm): {best['fa']:.1%}",
            f"Missed tamper (alarm class predicted as idle/knock): {best['miss']:.1%}"]

    X = Xext if best["ext"] else Xraw
    final = make_model(best["kind"], best["trees"], best["depth"], best["leaf"]).fit(X, y)
    names = FEATURES + DERIVED
    rep += ["", "Feature importance"] + [f"  {k:12s} {v:.3f}" for k, v in
                                          sorted(zip(names, final.feature_importances_), key=lambda p: -p[1])]
    text = "\n".join(rep)
    print("\n" + text)
    REPORT.write_text(text + "\n")

    export_header(final, classes, best["ext"], merged, OUT_H)
    print(f"\nWrote {OUT_H}  ({OUT_H.stat().st_size // 1024} KB)  and  {REPORT}")


main()

